{
	const FTimespan JstOffset = FTimespan::FromHours(9);
	constexpr uint64 HudKeyStatus = 0x48474131;
	constexpr uint64 HudKeyHelp = 0x48474132;
	constexpr uint64 HudKeyError = 0x48474133;
	/** How far the sea reaches (metres). */
	constexpr double FarM = 2000.0;
	/** The apron around the map: its half width and grid step (metres). The step divides the map's half size. */
	constexpr double ApronM = 1000.0;
	constexpr double ApronStepM = 8.0;
	constexpr double EyeHeightM = 1.6;

	/** Generated by tools/unreal/make_materials.py (BuildEditor.bat runs it after building). */
	const TCHAR* GroundMaterialPath = TEXT("/Game/Generated/M_HigataGround.M_HigataGround");
	const TCHAR* WaterMaterialPath = TEXT("/Game/Generated/M_HigataWater.M_HigataWater");

	/**
	 * Dry albedo by substrate (linear). The web build's colours scaled to plausible real albedos: dry sand
	 * about 0.28, mud about 0.14. The ground material darkens them where the flat is wet.
	 */
	FLinearColor SubstrateColor(const FString& Name)
	{
		if (Name == TEXT("sand")) return FLinearColor(0.28f, 0.28f, 0.266f);
		if (Name == TEXT("muddy_sand")) return FLinearColor(0.22f, 0.214f, 0.2f);
		if (Name == TEXT("gravel")) return FLinearColor(0.25f, 0.23f, 0.2f);
		if (Name == TEXT("channel")) return FLinearColor(0.11f, 0.108f, 0.1f);
		if (Name == TEXT("rock")) return FLinearColor(0.22f, 0.22f, 0.21f);
		return FLinearColor(0.14f, 0.138f, 0.128f); // mud
	}

	void ShowError(const FString& Text)
	{
		UE_LOG(LogTemp, Error, TEXT("[Higata] %s"), *Text);
		if (GEngine)
		{
			GEngine->AddOnScreenDebugMessage(HudKeyError, 600.f, FColor::Red, Text);
		}
	}

	/**
	 * Adds a quad's two triangles once per winding, so the face shows from either side. The procedural meshes
	 * are built in code with no material asset to mark them two-sided, and the ground is only ever seen from above.
	 */
	void AddQuadBothSides(TArray<int32>& Tris, int32 A, int32 B, int32 C, int32 D)
	{
		Tris.Append({A, B, C, A, C, D, A, C, B, A, D, C});
	}

	/** One flat rectangle (web-space corners, metres) as a procedural mesh section. */
	void MakeFlatSection(UProceduralMeshComponent* Mesh, int32 Section, double X0, double Z0, double X1, double Z1, double Y)
	{
		const TArray<FVector> Verts = {FHigataMap::ToUnreal(X0, Z0, Y), FHigataMap::ToUnreal(X1, Z0, Y), FHigataMap::ToUnreal(X1, Z1, Y),
			FHigataMap::ToUnreal(X0, Z1, Y)};
		TArray<int32> Tris;
		AddQuadBothSides(Tris, 0, 1, 2, 3);
		const TArray<FVector> Normals = {FVector::UpVector, FVector::UpVector, FVector::UpVector, FVector::UpVector};
		Mesh->CreateMeshSection_LinearColor(Section, Verts, Tris, Normals, TArray<FVector2D>(), TArray<FLinearColor>(),
			TArray<FProcMeshTangent>(), false);
	}
}

namespace HFL = HigataFlatLocal;

AHigataFlat::AHigataFlat()
{
	PrimaryActorTick.bCanEverTick = true;

	RootComponent = CreateDefaultSubobject<USceneComponent>(TEXT("Root"));

	Ground = CreateDefaultSubobject<UProceduralMeshComponent>(TEXT("Ground"));
	Ground->SetupAttachment(RootComponent);
	// Cooked synchronously: the walker is spawned right after and must land on it.
	Ground->bUseAsyncCooking = false;

	Surroundings = CreateDefaultSubobject<UProceduralMeshComponent>(TEXT("Surroundings"));
	Surroundings->SetupAttachment(RootComponent);

	Sea = CreateDefaultSubobject<UProceduralMeshComponent>(TEXT("Sea"));
	Sea->SetupAttachment(RootComponent);
	Sea->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	Sea->SetCastShadow(false);
}

void AHigataFlat::BeginPlay()
{
	Super::BeginPlay();

	FString Error;
	if (!FHigataMap::Load(MapId, Map, Error))
	{
		HFL::ShowError(TEXT("Map: ") + Error);
		return;
	}
	UGameInstance* GameInstance = GetGameInstance();
	UTideSubsystem* Tide = GameInstance ? GameInstance->GetSubsystem<UTideSubsystem>() : nullptr;
	if (!Tide || !Tide->LoadStation(Map.StationId))
	{
		HFL::ShowError(FString::Printf(TEXT("Tide: cannot load station %s (see the Output Log)"), *Map.StationId));
		return;
	}

	HideTemplateMeshes();
	BuildGround();
	BuildSurroundings();
	BuildSea();
	FindOrSpawnSun();
	bReady = true;
}

void AHigataFlat::HideTemplateMeshes()
{
	// The stock template levels put a floor and a backdrop of hills (static meshes, or a landscape) at the
	// origin, right where the flat goes. Hide every mesh and landscape not ours; keep the pawn and the sky.
	for (TActorIterator<AActor> It(GetWorld()); It; ++It)
	{
		AActor* Actor = *It;
		if (Actor == this || Actor->IsA<APawn>() || Actor->GetClass()->GetName().Contains(TEXT("Sky")))
		{
			continue;
		}
		TInlineComponentArray<UPrimitiveComponent*> Primitives(Actor);
		for (UPrimitiveComponent* Primitive : Primitives)
		{
			const bool bHide = Primitive->IsA<UStaticMeshComponent>() || Primitive->GetClass()->GetName().Contains(TEXT("Landscape"));
			if (bHide)
			{
				Primitive->SetHiddenInGame(true);
				Primitive->SetCollisionEnabled(ECollisionEnabled::NoCollision);
			}
			UE_LOG(LogTemp, Display, TEXT("[Higata] template %s: %s / %s (%s)"), bHide ? TEXT("hidden") : TEXT("kept"), *Actor->GetName(),
				*Primitive->GetName(), *Primitive->GetClass()->GetName());
		}
	}
}

UMaterialInterface* AHigataFlat::MakePlainMaterial(const FLinearColor& Color)
{
	// The engine's basic shape material has a "Color" parameter; good enough until the flat gets its own materials.
	UMaterialInterface* Base = LoadObject<UMaterialInterface>(nullptr, TEXT("/Engine/BasicShapes/BasicShapeMaterial.BasicShapeMaterial"));
	if (!Base)
	{
		return nullptr;
	}
	UMaterialInstanceDynamic* Mid = UMaterialInstanceDynamic::Create(Base, this);
	Mid->SetVectorParameterValue(TEXT("Color"), Color);
	return Mid;
}

void AHigataFlat::BuildGround()
{
	const int32 N = Map.N;
	const double Cell = Map.Cell();
	TArray<FVector> Verts;
	TArray<FVector> Normals;
	TArray<FVector2D> Uvs;
	TArray<FLinearColor> Colors;
	Colors.Reserve(N * N);
	Verts.Reserve(N * N);
	Normals.Reserve(N * N);
	Uvs.Reserve(N * N);
	for (int32 J = 0; J < N; ++J)
	{
		for (int32 I = 0; I < N; ++I)
		{
			const double X = -Map.Half() + I * Cell, Z = -Map.Half() + J * Cell;
			Verts.Add(FHigataMap::ToUnreal(X, Z, Map.GridHeight(I, J)));
			// Web normal (-dh/dx, 1, -dh/dz) becomes Unreal (X, Y, Z) = (-dh/dx, -dh/dz, 1).
			const double Dx = (Map.GridHeight(I + 1, J) - Map.GridHeight(I - 1, J)) / (2 * Cell);
			const double Dz = (Map.GridHeight(I, J + 1) - Map.GridHeight(I, J - 1)) / (2 * Cell);
			Normals.Add(FVector(-Dx, -Dz, 1.0).GetSafeNormal());
			Uvs.Add(FVector2D(static_cast<double>(I) / (N - 1), static_cast<double>(J) / (N - 1)));
			Colors.Add(HFL::SubstrateColor(Map.GridSubstrate(I, J)));
		}
	}
	TArray<int32> Tris;
	Tris.Reserve((N - 1) * (N - 1) * 12);
	for (int32 J = 0; J < N - 1; ++J)
	{
		for (int32 I = 0; I < N - 1; ++I)
		{
			const int32 A = J * N + I;
			HFL::AddQuadBothSides(Tris, A, A + 1, A + N + 1, A + N);
		}
	}
	Ground->CreateMeshSection_LinearColor(0, Verts, Tris, Normals, Uvs, Colors, TArray<FProcMeshTangent>(), true);
	if (UMaterialInterface* Generated = LoadObject<UMaterialInterface>(nullptr, HFL::GroundMaterialPath))
	{
		GroundMaterial = UMaterialInstanceDynamic::Create(Generated, this);
		Ground->SetMaterial(0, GroundMaterial);
		bGeneratedMaterials = true;
	}
	else
	{
		// A grey-beige close to the web build's wet sand.
		Ground->SetMaterial(0, MakePlainMaterial(FLinearColor(0.30f, 0.28f, 0.24f)));
	}
}

void AHigataFlat::BuildSurroundings()
{
	// A coarse apron out to ApronM: the map's edge profile continued outward (HeightAt clamps to the edge), so the
	// land runs on west and the sea bed east instead of the map ending in a cliff. Inside the map it is sunk 1 m
	// under the detailed ground; on the map's boundary it sits 2 cm below it.
	const double Step = HFL::ApronStepM;
	const int32 Count = FMath::RoundToInt32(2 * HFL::ApronM / Step) + 1;
	const double Inner = Map.Half() - 1e-6;
	TArray<FVector> Verts;
	TArray<FVector> Normals;
	TArray<FLinearColor> Colors;
	Verts.Reserve(Count * Count);
	Normals.Reserve(Count * Count);
	Colors.Reserve(Count * Count);
	for (int32 J = 0; J < Count; ++J)
	{
		for (int32 I = 0; I < Count; ++I)
		{
			const double X = -HFL::ApronM + I * Step, Z = -HFL::ApronM + J * Step;
			const bool bInside = FMath::Abs(X) < Inner && FMath::Abs(Z) < Inner;
			Verts.Add(FHigataMap::ToUnreal(X, Z, Map.HeightAt(X, Z) - (bInside ? 1.0 : 0.02)));
			const double Dx = (Map.HeightAt(X + Step, Z) - Map.HeightAt(X - Step, Z)) / (2 * Step);
			const double Dz = (Map.HeightAt(X, Z + Step) - Map.HeightAt(X, Z - Step)) / (2 * Step);
			Normals.Add(FVector(-Dx, -Dz, 1.0).GetSafeNormal());
			const int32 Gi = FMath::Clamp(FMath::RoundToInt32((X + Map.Half()) / Map.Cell()), 0, Map.N - 1);
			const int32 Gj = FMath::Clamp(FMath::RoundToInt32((Z + Map.Half()) / Map.Cell()), 0, Map.N - 1);
			Colors.Add(HFL::SubstrateColor(Map.GridSubstrate(Gi, Gj)));
		}
	}
	TArray<int32> Tris;
	Tris.Reserve((Count - 1) * (Count - 1) * 12);
	for (int32 J = 0; J < Count - 1; ++J)
	{
		for (int32 I = 0; I < Count - 1; ++I)
		{
			const int32 A = J * Count + I;
			HFL::AddQuadBothSides(Tris, A, A + 1, A + Count + 1, A + Count);
		}
	}
	Surroundings->CreateMeshSection_LinearColor(0, Verts, Tris, Normals, TArray<FVector2D>(), Colors, TArray<FProcMeshTangent>(), true);
	Surroundings->SetMaterial(0, GroundMaterial ? static_cast<UMaterialInterface*>(GroundMaterial.Get())
		: MakePlainMaterial(FLinearColor(0.22f, 0.21f, 0.19f)));
}

void AHigataFlat::BuildSea()
{
	// A level sheet moved up and down with the tide (Tick sets its height).
	HFL::MakeFlatSection(Sea, 0, -HFL::FarM, -HFL::FarM, HFL::FarM, HFL::FarM, 0.0);
	UMaterialInterface* Water = LoadObject<UMaterialInterface>(nullptr, HFL::WaterMaterialPath);
	Sea->SetMaterial(0, Water ? Water : MakePlainMaterial(FLinearColor(0.02f, 0.07f, 0.08f)));
}

void AHigataFlat::FindOrSpawnSun()
{
	for (TActorIterator<ADirectionalLight> It(GetWorld()); It; ++It)
	{
		SunLight = *It;
		break;
	}
	if (!SunLight)
	{
		SunLight = GetWorld()->SpawnActor<ADirectionalLight>();
		if (SunLight)
		{
			if (UDirectionalLightComponent* Light = Cast<UDirectionalLightComponent>(SunLight->GetLightComponent()))
			{
				Light->SetAtmosphereSunLight(true);
			}
		}
	}
	if (SunLight && SunLight->GetRootComponent())
	{
		SunLight->GetRootComponent()->SetMobility(EComponentMobility::Movable);
	}
}

void AHigataFlat::PlacePlayer()
{
	APlayerController* Pc = GetWorld()->GetFirstPlayerController();
	APawn* Previous = Pc ? Pc->GetPawn() : nullptr;
	if (!Previous)
	{
		return;
	}
	const double H = FMath::DegreesToRadians(Map.SpawnHeadingDeg);
	const double Yaw = FMath::RadiansToDegrees(FMath::Atan2(-FMath::Cos(H), -FMath::Sin(H)));
	const double GroundM = Map.HeightAt(Map.SpawnX, Map.SpawnZ);
	// The capsule's centre is 88 cm above the feet; start a few centimetres above the ground.
	const FVector Start = FHigataMap::ToUnreal(Map.SpawnX, Map.SpawnZ, GroundM + 0.93);

	FActorSpawnParameters Params;
	Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
	Walker = GetWorld()->SpawnActor<AHigataWalker>(Start, FRotator(0.0, Yaw, 0.0), Params);
	if (Walker)
	{
		Pc->UnPossess();
		Previous->Destroy();
		Pc->Possess(Walker);
	}
	else
	{
		// Fall back to the level's own pawn.
		Previous->SetActorLocation(FHigataMap::ToUnreal(Map.SpawnX, Map.SpawnZ, GroundM + HFL::EyeHeightM), false, nullptr,
			ETeleportType::TeleportPhysics);
	}
	Pc->SetControlRotation(FRotator(-8.0, Yaw, 0.0));
	bPlacedPlayer = true;
}

void AHigataFlat::HandleClockKeys()
{
	APlayerController* Pc = GetWorld()->GetFirstPlayerController();
	if (!Pc)
	{
		return;
	}
	if (Pc->WasInputKeyJustPressed(EKeys::T))
	{
		++ClockOffsetHours;
	}
	if (Pc->WasInputKeyJustPressed(EKeys::G))
	{
		--ClockOffsetHours;
	}
	if (Pc->WasInputKeyJustPressed(EKeys::R))
	{
		ClockOffsetHours = 0;
	}
}

double AHigataFlat::WetLevelAt(const FDateTime& Utc) const
{
	// wet(t) = max over the last day of tide(s) - 0.05 m/h * (t - s), never below the tide and at most 1.4 m above:
	// the same band the web build keeps by integrating wetLevel = min(max(tide, wet - 0.05 dt), tide + 1.4).
	const UTideSubsystem* Tide = GetGameInstance()->GetSubsystem<UTideSubsystem>();
	const double Now = Tide->GetLevelAt(Utc);
	double Wet = Now;
	for (int32 Step = 1; Step <= 24 * 6; ++Step)
	{
		const double Hours = Step / 6.0;
		Wet = FMath::Max(Wet, Tide->GetLevelAt(Utc - FTimespan::FromMinutes(10.0 * Step)) - 0.05 * Hours);
	}
	return FMath::Min(Wet, Now + 1.4);
}

void AHigataFlat::Tick(float DeltaSeconds)
{
	Super::Tick(DeltaSeconds);
	if (!bReady)
	{
		return;
	}
	if (!bPlacedPlayer)
	{
		PlacePlayer();
	}
	HandleClockKeys();

	const FDateTime Utc = FDateTime::UtcNow() + FTimespan::FromHours(ClockOffsetHours);
	const double Ms = UTideSubsystem::ToEpochMs(Utc);

	UTideSubsystem* Tide = GetGameInstance()->GetSubsystem<UTideSubsystem>();
	const double Level = Tide->GetLevelAt(Utc);
	const bool bRising = Tide->GetRateAt(Utc) >= 0;
	Sea->SetRelativeLocation(FVector(0.0, 0.0, Level * 100.0));
	const double WetLevel = WetLevelAt(Utc);
	double DepthM = 0.0;
	if (Walker)
	{
		Walker->SetWaterLevelM(Level);
		DepthM = Walker->GetWaterDepthM();
		if (Walker->GetActorLocation().Z < -5000.0)
		{
			// Fell off the world somehow: back to the start.
			bPlacedPlayer = false;
			Walker->SetActorLocation(FHigataMap::ToUnreal(Map.SpawnX, Map.SpawnZ, Map.HeightAt(Map.SpawnX, Map.SpawnZ) + 0.93), false, nullptr,
				ETeleportType::TeleportPhysics);
			bPlacedPlayer = true;
		}
	}
	if (GroundMaterial)
	{
		GroundMaterial->SetScalarParameterValue(TEXT("WetLevelM"), static_cast<float>(WetLevel));
	}

	const HigataTide::FSunPosition SunPos = HigataTide::ComputeSunPosition(Ms, Map.OriginLat, Map.OriginLon);
	if (SunLight)
	{
		// Toward the sun in web space is (sin az cos el, sin el, -cos az cos el); in Unreal (X east, Y south, Z up):
		const double El = FMath::DegreesToRadians(SunPos.Elevation), Az = FMath::DegreesToRadians(SunPos.Azimuth);
		const FVector ToSun(FMath::Sin(Az) * FMath::Cos(El), -FMath::Cos(Az) * FMath::Cos(El), FMath::Sin(El));
		SunLight->SetActorRotation((-ToSun).Rotation());
	}

	if (GEngine)
	{
		const FString Offset = ClockOffsetHours == 0 ? TEXT("now") : FString::Printf(TEXT("now %+d h"), ClockOffsetHours);
		GEngine->AddOnScreenDebugMessage(HFL::HudKeyStatus, 1.f, FColor::Cyan,
			FString::Printf(TEXT("Hashirimizu  %s JST (%s)   tide %+.2f m %s   wet up to %+.2f m   sun %.0f deg%s"),
				*(Utc + HFL::JstOffset).ToString(TEXT("%m/%d %H:%M")), *Offset, Level, bRising ? TEXT("rising") : TEXT("falling"), WetLevel,
				SunPos.Elevation, bGeneratedMaterials ? TEXT("") : TEXT("   (plain materials: run BuildEditor.bat)")));
		const FString Wading = DepthM > 0.01 ? FString::Printf(TEXT("   in water %.2f m%s"), DepthM, DepthM > 1.0 ? TEXT(" (over the waders)") : TEXT("")) : FString();
		GEngine->AddOnScreenDebugMessage(HFL::HudKeyHelp, 1.f, FColor::White,
			FString::Printf(TEXT("[T] +1 hour  [G] -1 hour  [R] now    WASD + mouse: walk  Shift: run  F: fly (E / Q up / down)%s"), *Wading));
	}
}
