// Golden fixtures for the C++ port of the habitat and the spawner (Source/HigataSim), written by the WEB build.
//
// Run inside a checkout of Gerupamasini/gerupamasini (the web build), from its root:
//   mkdir -p tests/unit/_tmp && cp <this repo>/tools/golden/spawn_golden.test.ts tests/unit/_tmp/
//   OUT=<this repo> npx vitest run tests/unit/_tmp/spawn_golden.test.ts
// It writes, into OUT:
//   Content/Data/maps/hashirimizu/features.u8   per coarse cell: the standing features (bit 0 eelgrass, 1 eelgrass_edge, 2 bare)
//   tests/sim/fixtures/hashirimizu_spawn.txt     scenarios: env, habitat tags, spawn requests and the generated individuals
import { it } from 'vitest';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';
import { MapSchema } from '../../../src/data/schemas/map';
import { SpeciesSchema, type SpeciesDef } from '../../../src/data/schemas/species';
import { Terrain } from '../../../src/world/Terrain';
import { Habitat } from '../../../src/world/Habitat';
import { AmamoMeadow } from '../../../src/world/amamo/AmamoMeadow';
import { LAYOUTS } from '../../../src/world/maps/hashirimizu';
import { hashInts } from '../../../src/core/Rng';
import { TideModel, type TideStationData } from '../../../src/tide/TideModel';
import { sunPosition, timeOfDay } from '../../../src/world/Sun';
import { jstParts, seasonOf } from '../../../src/core/Time';
import { Spawner, type SpawnEnv } from '../../../src/creatures/Spawner';
import type { TidePhase } from '../../../src/data/schemas';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const out = (process.env.OUT ?? '.') + '/';
const json = (rel: string) => JSON.parse(readFileSync(root + 'public/data/' + rel, 'utf8'));

it('writes the hashirimizu habitat bake and spawn fixtures', () => {
  const map = MapSchema.parse(json('maps/hashirimizu.json'));
  const h = PNG.sync.read(readFileSync(root + 'public/data/maps/' + map.height.file));
  const s = PNG.sync.read(readFileSync(root + 'public/data/maps/' + map.substrate.file));
  const n = map.resolution, heights = new Float32Array(n * n), substrate = new Uint8Array(n * n);
  for (let i = 0; i < n * n; i++) {
    heights[i] = map.height.min_tp_m + (((h.data[i * 4] << 8) | h.data[i * 4 + 1]) / 65535) * (map.height.max_tp_m - map.height.min_tp_m);
    substrate[i] = s.data[i * 4];
  }
  const terrain = new Terrain({ n, size: map.size_m, heights, substrate }, map.substrate.palette, []);
  const habitat = new Habitat(terrain, map.habitat?.coarse_m ?? 5, []);
  const layout = LAYOUTS[map.layout!];
  const mapSeed = hashInts(...[...map.id].map((c) => c.charCodeAt(0)), 20261006);
  const meadow = new AmamoMeadow(terrain, habitat, mapSeed, layout.meadow);
  habitat.setFeatures((x, z) => ({ eelgrass: meadow.coverAt(x, z), zone: meadow.suitability(x, z) }));

  const bits: Record<string, number> = { eelgrass: 1, eelgrass_edge: 2, bare: 4 };
  const features = new Uint8Array(habitat.cn * habitat.cn);
  habitat.featureTags.forEach((tags, k) => { for (const t of tags) features[k] |= bits[t]; });
  mkdirSync(out + 'Content/Data/maps/hashirimizu', { recursive: true });
  writeFileSync(out + 'Content/Data/maps/hashirimizu/features.u8', features);

  const manifest = json('manifest.json') as { species: string[] };
  const species: SpeciesDef[] = manifest.species.map((id) => SpeciesSchema.parse(json(`species/${id}.json`)));
  const tide = new TideModel(json(`tide/stations/${map.station}.json`) as TideStationData);
  const amp = tide.maxAmplitude();
  const spawner = new Spawner(habitat, species, new Set());

  const lines = ['# Generated by tools/golden/spawn_golden.test.ts in the web build. Do not edit by hand.'];
  const players: [number, number][] = [[map.spawnStart.x, map.spawnStart.z], [0, 0], [20, -15], [-10, 25], [35, 30]];
  const start = Date.UTC(2026, 0, 3, 1, 7);
  for (let k = 0; k < 60; k++) {
    const gameMs = start + k * (6 * 86400000 + 5 * 3600000 + 23 * 60000);
    const level = tide.level(gameMs), rate = tide.rate(gameMs);
    habitat.update(gameMs, level);
    const sp = sunPosition(gameMs, map.origin.lat, map.origin.lon);
    const tidePhase: TidePhase = level < -0.35 * amp ? 'low' : level > 0.35 * amp ? 'high' : rate >= 0 ? 'rising' : 'falling';
    const env: SpawnEnv = { tod: timeOfDay(sp.elevation, jstParts(gameMs).hour), season: seasonOf(gameMs), tidePhase, mapId: map.id, gameMs, day: Math.floor(gameMs / 86400000) };
    const [px, pz] = players[k % players.length];
    const minDist = k % 3 === 0 ? 0 : 10;
    lines.push(`scenario ${k} ${gameMs} ${px} ${pz} ${minDist} ${String(level)} ${env.tod} ${env.season} ${env.tidePhase} ${env.day}`);
    if (k % 10 === 0) lines.push(`tags ${habitat.tags.map((t) => t.join(',') || '-').join(' ')}`);
    for (const req of spawner.plan(px, pz, env, [], minDist, 1)) {
      const ind = spawner.create(req, gameMs);
      lines.push(['req', req.species.id, req.ruleIndex, req.cell, req.seed, String(req.x), String(req.z), ind.id, String(ind.length_mm), String(ind.weight_g),
        ind.sex, ind.stage, ind.traits.join(',') || '-', ind.gravid ? 1 : 0, ind.dress ? 1 : 0, String(ind.heading)].join(' '));
    }
  }
  mkdirSync(out + 'tests/sim/fixtures', { recursive: true });
  writeFileSync(out + 'tests/sim/fixtures/hashirimizu_spawn.txt', lines.join('\n') + '\n');
});
